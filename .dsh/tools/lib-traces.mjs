/**
 * lib-traces.mjs — 修订痕迹（D10）判定的**唯一定义处**
 *
 * 为什么必须共享：实测踩过一次坑——两个脚本各自内联了一份 `TRACE_RE`，
 * 一个含「版本历史」且**没有任何误报过滤**，另一个已有
 * 四层过滤并排除了「版本历史」是页面名的情况。结果是两个工具对**同一份文档**
 * 给出相反判定：419 被判「残留痕迹 10 行」进架构师队列，而核验器对它报 0 行。
 *
 * 这类"两个工具各说各话"是清洗流程里最难查的问题——它不会报错，只会让结论互相矛盾。
 * 因此 D10 的检出式与全部误报排除规则都收敛到本模块。
 *
 * 与 QA 契约 D10 的检索式保持一致：`修订|变更记录|版本历史|原为|上一轮|就地注记|本版`。
 */

/**
 * 修订痕迹检出词。
 *
 * 若干处必须排除，否则误报：
 *  ① 裸「更正」：`口径更正`/`归因更正`/`修复落点更正` 是**设计动作的描述**
 *     （要纠正的那个错口径本身就是设计信息），不是修订史。
 *  ②「版本历史」作为**功能 / 页面名称**（`版本历史（VersionHistory.svelte）`、
 *     `查看文档版本历史`、`版本历史页面`）——它是设计对象，不是本文件的修订史。
 *  ③「变更记录」作为**被设计的功能**（`变更记录（追加式、不重写历史）`）同理。
 *
 * ---- 两次**补漏报**（方向安全，但都来自实测被打脸）----
 *
 * ④ **`更正注记` 整节漏报**：实测 `0.1.18-v4` 有 `## 更正注记`，词表**不含「更正」任何形态**，
 *    于是报 0 命中。补 `更正(注记|说明|声明)`。
 *    ⚠️ 注意**只补带后缀的形态**，不补裸「更正」——理由见上面 ①：
 *    `口径更正`/`归因更正` 是设计动作的描述，补裸词会把它们全打成痕迹。
 *
 * ⑤ **「第几版改的」型表达漏报**：实测两份重写稿里残留
 *    `v3 草案的失败路径…`、`v4 修正画法`、`过程记录（v2 起变更）`、`## 四、可行性分析（含探针数据，v2 重写）`。
 *    这类表达**正文不需要版本号也成立**（`v4 修正画法` → `画法已订正`：内容留、版本去），
 *    所以是真痕迹。补 `v\d+(?:\.\d+)*\s*(修正|订正|重写|草案)`。
 *    ⚠️ **不补 `原 vN` / 裸 `vN`**：实测 `目录治理设计方案` 的 `v1/v2/v3` 指**被收敛的那三份面板卡文件本身**
 *    （该文档的主题就是收敛它们），`v2 基线` 指**被引上游发布的版本**——这些是**被引对象**，不是自指痕迹。
 *    补了会造成大面积误报，**而误报会让人开始忽略判据**，比漏报更糟。
 *
 * 判据：「版本历史 / 变更记录」只有指向**本文档自身**的修订史时才算痕迹。
 */
export const TRACE_RE = /修订记录|变更记录|修订历史|修订摘要|原为.{0,40}(现改|改为)|就地注记|就地追加|逐字保留|上一轮|上轮|本版(新增|修订|摘要)|回环响应|QA\s*的\s*[FN R]\d|按\s*QA|更正(注记|说明|声明)|v\d+(?:\.\d+)*\s*(修正|订正|重写|草案)/

/** 指向本文档自身修订史的判定（用于排除"版本历史"是页面名的情况） */
export const SELF_REVISION_HEADING_RE = /^#{2,6}\s*[^\n]{0,24}(版本历史|变更记录|修订记录|修订历史)\s*$/
export const SELF_REVISION_LABEL_RE = /(版本历史|变更记录|修订记录)\s*[:：]/

/**
 * 误报排除（两处，都来自实测）：
 *
 * ① **痕迹词出现在被引用文件名里**：0.1.23 实施清单第 15 行是 `docs/术语变更记录.md`——
 *    那是一份**术语台账文件**，不是本文的修订记录章节。
 * ② **痕迹词作为表格单元格的值**：上例中同一行还有一列取值就是「变更记录」（指该文件的类型），
 *    去掉反引号段后裸词「变更记录」仍会命中。
 *
 * 因此判定规则收紧为：**只认"单独成节标题"或"出现在散文里"的痕迹**，
 * 表格行内作为单元格值的痕迹词不算。真正的修订章节有自己的标题，不会只靠一个表格单元格标记。
 */
export const TRACE_FALSE_POSITIVE_RE = /`[^`]*\.md`|`[^`]*术语[^`]*`/

/** 该行是否为多单元格表格行（痕迹词很可能只是某个格子的取值） */
export function isTableValueLine(l) {
  const cells = l.split('|').filter((c) => c.trim() !== '')
  return cells.length >= 2
}

/**
 * 判断一行是否为「修订痕迹」。
 *
 * @param {string} line       待判定的行
 * @param {object} [opts]
 * @param {number} [opts.headWindow] 头部若干行内视为允许（版本号只许在头部留 1 行）
 * @param {number} [opts.lineNo]     当前行号（1 起）
 * @returns {boolean}
 */
export function isTraceLine(line, opts = {}) {
  if (!TRACE_RE.test(line)) return false

  const isHeading = /^#{1,6}\s/.test(line)
  const selfRevision = SELF_REVISION_HEADING_RE.test(line) || SELF_REVISION_LABEL_RE.test(line)

  // ① 排除"痕迹词出现在被引用文件名里"的误报
  const stripped = line.replace(/`[^`]*`/g, '')
  if (!TRACE_RE.test(stripped) && !SELF_REVISION_LABEL_RE.test(stripped)) return false

  // ② 排除"痕迹词只是表格某个格子的取值"——真正的修订章节有自己的标题
  if (!isHeading && !selfRevision && isTableValueLine(stripped)) return false

  // ③ 排除"版本历史 / 变更记录"是**被设计的功能名**（页面、组件、按钮、缺口项）
  const isFeatureName = /版本历史|变更记录/.test(line) &&
    !SELF_REVISION_HEADING_RE.test(line) &&
    !SELF_REVISION_LABEL_RE.test(line) &&
    /VersionHistory|版本历史页面|版本历史\s*\(|查看文档版本历史|文档版本历史|版本历史、|变更记录（追加式/.test(line)
  if (isFeatureName) return false

  return true
}
